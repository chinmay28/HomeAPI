// pixelGlyph returns the column bytes for r. Runes outside the table fall
// back to a box so missing coverage is visible rather than silently blank;
// the em dash and en dash, which the footer uses for "no value", are drawn
// as a full-width bar.
func pixelGlyph(r rune) [pixelGlyphW]byte {
	switch r {
	case '—', '–': // — –
		return [pixelGlyphW]byte{0x08, 0x08, 0x08, 0x08, 0x08}
	case ' ':
		return pixelFont[0]
	}
	if r < pixelFirstRun || int(r-pixelFirstRun) >= len(pixelFont) {
		return [pixelGlyphW]byte{0x7F, 0x41, 0x41, 0x41, 0x7F} // □
	}
	return pixelFont[r-pixelFirstRun]
}

// PixelTextWidth returns the width in pixels of s set in the pixel font,
// excluding the trailing spacing column.
func PixelTextWidth(s string, bold bool) int {
	n := 0
	for range s {
		n++
	}
	if n == 0 {
		return 0
	}
	if bold {
		return n*pixelBoldAdv - 1
	}
	return n*pixelAdvance - 1
}

// DrawPixelText sets s in the pixel font with its top-left corner at (x, y)
// and returns the x just past the last glyph's spacing column. Bold draws
// each glyph twice, one pixel apart, for a 6-px-wide 7-px-advance letter.
func (f *Frame) DrawPixelText(x, y int, s string, black, bold bool) int {
	for _, r := range s {
		g := pixelGlyph(r)
		for col := 0; col < pixelGlyphW; col++ {
			bits := g[col]
			for row := 0; row < pixelGlyphH; row++ {
				if bits&(1<<uint(row)) == 0 {
					continue
				}
				f.Set(x+col, y+row, black)
				if bold {
					f.Set(x+col+1, y+row, black)
				}
			}
		}
		if bold {
			x += pixelBoldAdv
		} else {
			x += pixelAdvance
		}
	}
	return x
}

// ── Outline font ────────────────────────────────────────────────────────────
//
// DejaVu Sans Condensed Bold (Bitstream Vera licence; see fonts/LICENSE).
// Condensed so six digits and a separator fit a 120-px tile; heavy strokes
// survive the 1-bit threshold; tabular figures line prices up across tiles.
// Glyphs are rasterised unhinted at the target size and thresholded at 50 %
// coverage. Only 17 px and 20 px have been checked visually.

//go:embed fonts/DejaVuSansCondensed-Bold.ttf
var dejaVuCondensedBold []byte

var (
	outlineOnce sync.Once
	outlineFont *sfnt.Font
	outlineErr  error
)

// loadOutlineFont parses the embedded face once. Parsing is cheap but not
// free, and the parsed *sfnt.Font is safe to share; the per-size Face is not,
// so faces are created per call.
func loadOutlineFont() (*sfnt.Font, error) {
	outlineOnce.Do(func() {
		outlineFont, outlineErr = opentype.Parse(dejaVuCondensedBold)
		if outlineErr != nil {
			outlineErr = fmt.Errorf("parsing embedded font: %w", outlineErr)
		}
	})
	return outlineFont, outlineErr
}

// outlineFace returns a face at the given pixel size. It must not be shared
// across goroutines.
func outlineFace(px float64) (font.Face, error) {
	f, err := loadOutlineFont()
	if err != nil {
		return nil, err
	}
	face, err := opentype.NewFace(f, &opentype.FaceOptions{
		Size:    px,
		DPI:     72,
		Hinting: font.HintingNone,
	})
	if err != nil {
		return nil, fmt.Errorf("creating %gpx face: %w", px, err)
	}
	return face, nil
}

// OutlineTextWidth returns the advance width in whole pixels of s at px.
func OutlineTextWidth(px float64, s string) (int, error) {
	face, err := outlineFace(px)
	if err != nil {
		return 0, err
	}
	defer face.Close()
	return font.MeasureString(face, s).Ceil(), nil
}

// DrawOutlineText rasterises s with its pen at (x, baseline), thresholds the
// coverage at 50 % and paints the surviving pixels. Pixels outside clip are
// dropped, so text can never spill out of its slot into a neighbour. It
// returns the pen x after the last glyph.
func (f *Frame) DrawOutlineText(px float64, x, baseline int, s string, black bool, clip image.Rectangle) (int, error) {
	face, err := outlineFace(px)
	if err != nil {
		return x, err
	}
	defer face.Close()

	bounds, adv := font.BoundString(face, s)
	// Pad the scratch canvas by a pixel each side: thresholded coverage can
	// land on the boundary rows of the glyph box.
	r := image.Rect(bounds.Min.X.Floor()-1, bounds.Min.Y.Floor()-1, bounds.Max.X.Ceil()+1, bounds.Max.Y.Ceil()+1)
	if r.Empty() {
		return x + adv.Ceil(), nil
	}
	canvas := image.NewAlpha(r)
	d := font.Drawer{
		Dst:  canvas,
		Src:  image.Opaque,
		Face: face,
		Dot:  fixed.Point26_6{},
	}
	d.DrawString(s)

	for cy := r.Min.Y; cy < r.Max.Y; cy++ {
		for cx := r.Min.X; cx < r.Max.X; cx++ {
			if canvas.AlphaAt(cx, cy).A < 0x80 {
				continue
			}
			px, py := x+cx, baseline+cy
			if !image.Pt(px, py).In(clip) {
				continue
			}
			f.Set(px, py, black)
		}
	}
	return x + adv.Ceil(), nil
}
